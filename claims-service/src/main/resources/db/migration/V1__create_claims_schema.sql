CREATE TABLE public.claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_amount NUMERIC(12, 2) NOT NULL,
    claim_number VARCHAR(255) NOT NULL,
    claim_type VARCHAR(255) NOT NULL,
    customer_id VARCHAR(255) NOT NULL,
    policy_number VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT uk_claims_claim_number UNIQUE (claim_number)
);

CREATE TABLE public.outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_id VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    event_id VARCHAR(36) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    payload TEXT NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT uk_outbox_events_event_id UNIQUE (event_id)
);

CREATE TABLE public.processed_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(36) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    processed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_processed_events_event_id UNIQUE (event_id)
);

CREATE TABLE public.replay_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    event_id VARCHAR(100),
    event_type VARCHAR(100),
    outcome VARCHAR(30) NOT NULL,
    reason VARCHAR(500)
);
